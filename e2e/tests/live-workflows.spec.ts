import { test, expect } from '@playwright/test';

test('live PR and sprint results are retrieved and rendered with observed node traces', async ({ page, request }) => {
  const token = process.env.SPRINTGRAPH_TEST_TOKEN;
  const project = Number(process.env.SPRINTGRAPH_PROJECT_ID);
  const number = Number(process.env.SPRINTGRAPH_PR_NUMBER);
  const sprint = process.env.SPRINTGRAPH_SPRINT_ID;
  const geminiResult = Number(process.env.SPRINTGRAPH_GEMINI_RESULT_ID || 0);
  if (!token || !project || !number || !sprint) throw new Error('Use scripts/verify_live_browser.py to supply a short-lived session.');
  const headers = { Authorization: `Bearer ${token}` };
  const prefix = `http://localhost:8000/api/projects/${project}`;
  const configResponse = await request.get('http://localhost:8000/api/settings', { headers });
  expect(configResponse.ok()).toBeTruthy();
  const config = await configResponse.json();
  expect(config.mode).toBe('live');
  expect(config.llm_provider).toBe(geminiResult ? 'openai-compatible' : 'demo');
  expect(config.llm_inference_enabled).toBe(Boolean(geminiResult));
  const prResponse = await request.get(`${prefix}/results/pull_request`, { headers });
  const sprintResponse = await request.get(`${prefix}/results/sprint_summary`, { headers });
  expect(prResponse.ok()).toBeTruthy();
  expect(sprintResponse.ok()).toBeTruthy();
  const pr = (await prResponse.json()).find((r: { id: number; evidence: { number: number } }) => r.evidence.number === number && (!geminiResult || r.id === geminiResult));
  const summary = (await sprintResponse.json()).find((r: { provider_id: string }) => r.provider_id === sprint);
  expect(pr, 'Run the live workflow verifier before the browser check').toBeTruthy();
  expect(summary).toBeTruthy();
  const submitted: string[] = [];
  const errors: string[] = [];
  page.on('request', req => { if (req.method() !== 'GET') submitted.push(req.method()); });
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(session => sessionStorage.setItem('sprintgraph-token', session), token);
  await page.goto('/pull-requests');
  await expect(page.getByRole('heading', { name: 'Pull Requests', exact: true })).toBeVisible();
  await page.getByLabel('Project', { exact: true }).selectOption(String(project));
  await expect(page.getByText('live environment', { exact: true })).toBeVisible();
  await expect(page.getByText(`Inference: ${geminiResult ? 'openai-compatible' : 'demo'}`, { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: pr.evidence.title, exact: true }).first()).toBeVisible();
  await expect(page.getByText(pr.analysis.summary, { exact: true }).first()).toBeVisible();
  await page.getByRole('link', { name: 'Sprint Insights', exact: true }).click();
  await page.getByLabel('Project', { exact: true }).selectOption(String(project));
  await expect(page.getByRole('heading', { name: summary.evidence.name, exact: true })).toBeVisible();
  await expect(page.getByText(summary.analysis.summary, { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Workflow Activity', exact: true }).click();
  await page.getByLabel('Project', { exact: true }).selectOption(String(project));
  const response = await request.get(`${prefix}/activity`, { headers });
  expect(response.ok()).toBeTruthy();
  const event = (await response.json()).find((e: { status: string; executions: { result?: { provider_id: string; analysis: { summary: string } } }[] }) =>
    e.status === 'succeeded' && e.executions.some(x => x.result?.provider_id === pr.provider_id && x.result?.analysis.summary === pr.analysis.summary));
  expect(event).toBeTruthy();
  const row = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: `#${event.id} ·` }) });
  await row.locator('summary').first().click();
  await expect(row.getByText('Nodes: classify (succeeded) → collect (succeeded) → pull_request (succeeded) → validate (succeeded)', { exact: true }).first()).toContainText('classify (succeeded) → collect (succeeded) → pull_request (succeeded) → validate (succeeded)');
  await expect(row.locator('pre')).toContainText(pr.provider_id);
  expect(errors).toEqual([]);
  expect(submitted, 'Browser verification must only retrieve persisted results').toEqual([]);
});
